#!/usr/bin/env bash
# Na Fir-Chlis – a Nord i3wm theme · lundie.io
# Route odd-numbered workspaces to the secondary output and even-numbered ones
# to the primary, whenever exactly two monitors are active.
#
# i3 accepts `workspace <name> output <output>` only as a *configuration*
# directive. Sent over IPC it is parsed as a plain workspace switch – the
# trailing `output ...` clause is discarded and i3 still answers {"success":true}
# – so the assignments have to reach i3 through its config rather than i3-msg.
# They are written to a fragment that the main config includes, and i3 is
# restarted to load it.
#
# Note that i3 has no `number` keyword in this directive: assignments match on
# the workspace *name*, so the names are read back out of the main config and
# stay in step automatically if they are renamed there.
#
# The restart is guarded – it happens only when the fragment's contents actually
# change – because the `exec_always` that runs this script would otherwise loop.
#
# Monitors come from `xrandr --listmonitors` rather than from connected outputs,
# because RandR monitors are what i3 itself keys off: one output split with
# `xrandr --setmonitor` is two screens to i3, and a single output driving two
# panels is one.
set -euo pipefail

command -v xrandr >/dev/null 2>&1 || exit 0
command -v i3-msg >/dev/null 2>&1 || exit 0

config_dir="${XDG_CONFIG_HOME:-${HOME}/.config}/i3"
fragment="${config_dir}/workspace-outputs.conf"

# Follow the Stow symlink to the tracked config, which is where the workspace
# names live.
main_config="$(readlink -f "${config_dir}/config" 2>/dev/null || true)"
[[ -r "${main_config}" ]] || exit 0

mapfile -t monitors < <(xrandr --listmonitors | awk 'NR > 1 {print $NF}')
primary_output="$(xrandr --listmonitors | awk 'NR > 1 && $2 ~ /\*/ {print $NF; exit}')"

secondary_output=""
if [[ "${#monitors[@]}" -eq 2 ]]; then
  [[ -n "${primary_output}" ]] || primary_output="${monitors[0]}"
  for output in "${monitors[@]}"; do
    if [[ "${output}" != "${primary_output}" ]]; then
      secondary_output="${output}"
      break
    fi
  done
fi

tmp_fragment="$(mktemp)"
trap 'rm -f "${tmp_fragment}"' EXIT

{
  printf '# Generated by i3-workspace-outputs.sh – edits here are overwritten.\n'
  if [[ -n "${secondary_output}" ]]; then
    printf '# Odd workspaces -> %s (secondary), even -> %s (primary).\n' \
      "${secondary_output}" "${primary_output}"
    # `set $wsN "N|label"` lines in the main config give the number and the name.
    while IFS=$'\t' read -r number name; do
      [[ -n "${number}" && -n "${name}" ]] || continue
      if (( number % 2 == 0 )); then
        printf 'workspace "%s" output %s\n' "${name}" "${primary_output}"
      else
        printf 'workspace "%s" output %s\n' "${name}" "${secondary_output}"
      fi
    done < <(awk '
      $1 == "set" && $2 ~ /^\$ws[0-9]+$/ {
        number = substr($2, 4)
        name = $0
        sub(/^[[:space:]]*set[[:space:]]+\$ws[0-9]+[[:space:]]+/, "", name)
        gsub(/^"|"$/, "", name)
        print number "\t" name
      }' "${main_config}")
  else
    printf '# Not exactly two monitors – no assignments, so i3 places\n'
    printf '# workspaces on whichever output has focus.\n'
  fi
} > "${tmp_fragment}"

# Only restart i3 when the assignments changed, or exec_always re-triggers this
# script and the restart loops.
if ! cmp -s "${tmp_fragment}" "${fragment}"; then
  mkdir -p "${config_dir}"
  mv "${tmp_fragment}" "${fragment}"
  trap - EXIT
  i3-msg restart >/dev/null 2>&1 || true
fi
